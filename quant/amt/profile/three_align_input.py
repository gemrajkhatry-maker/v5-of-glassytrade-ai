"""ThreeAlignInput protocol — minimal contract for three-align gate logic.

This defines the *exact* subset of AMTResult fields required by three_align_check(),
not the full AMTResult interface. It enables type safety, testability, and contract clarity.
"""

from __future__ import annotations

from typing import Protocol, Optional, List


class ThreeAlignInput(Protocol):
    @property
    def cvd_slope(self) -> float | None: ...
    @property
    def cvd_divergence(self) -> str | None: ...
    @property
    def session_vwap(self) -> float | None: ...
    @property
    def session_vwap(self) -> float | None: ...
    @property
    def lvn_play(self) -> bool | None: ...
    @property
    def prior_poc(self) -> float | None: ...
    @property
    def value_area_high(self) -> float | None: ...
    @property
    def value_area_low(self) -> float | None: ...
    @property
    def poc(self) -> float | None: ...
    @property
    def market_state(self) -> str | None: ...
    @property
    def price_velocity(self) -> float | None: ...
    @property
    def leg_poc(self) -> float | None: ...
    @property
    def leg_vah(self) -> float | None: ...
    @property
    def leg_val(self) -> float | None: ...
    @property
    def dev_poc(self) -> float | None: ...
    @property
    def dev_vah(self) -> float | None: ...
    @property
    def dev_val(self) -> float | None: ...
    @property
    def hvns(self) -> List[float] | None: ...
    @property
    def lvns(self) -> List[float] | None: ...
    @property
    def leg_lvns(self) -> List[float] | None: ...
